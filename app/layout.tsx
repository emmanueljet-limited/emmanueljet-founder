import type { Metadata } from 'next';
import type { ReactNode } from 'react';
import { Geist, Geist_Mono } from 'next/font/google';

import './globals.css';
import { LanguageProvider } from '@/contexts/LanguageContext';

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

/**
 * Metadata configuration for the root application layout.
 */
export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

/**
 * Props for the root layout component.
 */
export interface IRootLayoutProps {
  /**
   * The page content rendered within the layout.
   */
  readonly children: ReactNode;
}

/**
 * Root layout component providing base styling and language context.
 *
 * @param props - Layout component properties.
 * @returns The rendered HTML document structure.
 */
const RootLayout = ({ children }: IRootLayoutProps) => {
  return (
    <html
      lang='en'
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className='min-h-full flex flex-col'>
        <LanguageProvider>{children}</LanguageProvider>
      </body>
    </html>
  );
};

export default RootLayout;
